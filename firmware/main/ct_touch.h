// จอสัมผัส XPT2046 บน SPI3 — การลากตามแนวนอน และการแตะที่รู้ตำแหน่งหยาบๆ
//
// เดิมรับแค่การลาก (ADR-0007) · การแตะถูกเพิ่มเข้ามาเพื่อตอบคำขออนุญาต ซึ่งเป็นคำถาม
// ที่มีคำตอบสองทางและกดผิดทางแล้วเสียหาย — ทิศของการลากไม่ใช่ภาษาที่พูดเรื่องนี้ได้
// อย่างปลอดภัย (ADR-0014) · ค่าคงที่ทั้งหมดมาจากการวัดบอร์ดจริง (layout.toml [touch])
#pragma once

#include <stdbool.h>

// ค่าตัวเลขไม่มีความหมาย และตั้งใจไม่ให้เป็น -1/+1 — ทิศของนิ้วกับทิศที่หน้าเดินไป
// สวนทางกัน (ปัดซ้ายคือไปหน้า *ถัดไป*) ตัวเลขที่ดูเหมือนใช้ต่อได้เลยจึงเป็นกับดัก
typedef enum {
    CT_SWIPE_NONE = 0,
    CT_SWIPE_LEFT,   // นิ้วลากจากขวาไปซ้าย
    CT_SWIPE_RIGHT,  // นิ้วลากจากซ้ายไปขวา
} ct_swipe_t;

// ตั้งบัส SPI3 แล้วตรวจว่าชิปมีจริง — คืน false เมื่อบอร์ดรุ่นย่อยนี้ไม่ได้บัดกรีมันมา
//
// swipe เป็นส่วนเสริมที่ขาดได้ (ADR-0007) ผู้เรียกต้องเดินต่อได้เมื่อได้ false —
// page rotation ไม่ได้พึ่งไฟล์นี้เลย
bool ct_touch_init(void);

// ท่าทางหนึ่งท่าที่เพิ่งจบ — เป็นได้อย่างใดอย่างหนึ่ง หรือไม่เป็นอะไรเลย
typedef struct {
    ct_swipe_t swipe;  // CT_SWIPE_NONE เมื่อไม่ใช่การปัด
    bool tap;          // แตะแล้วยกโดยแทบไม่ขยับ
    // ตำแหน่งที่นิ้ว *ลง* ไม่ใช่ที่มันยกขึ้น — มีความหมายเมื่อ `tap` เป็นจริงเท่านั้น
    //
    // จุดลงคือจุดที่คนเล็งไว้ ส่วนจุดยกคือจุดที่นิ้วไหลไปถึงตอนถอนออก การเล็งปุ่มแล้ว
    // นิ้วไหลออกนอกปุ่มระหว่างยก เป็นการกดปุ่มนั้น ไม่ใช่การกดข้างๆ มัน
    int x, y;
} ct_touch_event_t;

// เดินเวลาไป `elapsed_ms` แล้วคืนสิ่งที่ *เพิ่งจบ* — คืนค่าเมื่อยกนิ้วเท่านั้น
// ไม่ใช่ระหว่างลาก เพราะการปัดยาวครั้งเดียวต้องเปลี่ยนหน้าครั้งเดียว
//
// อ่านชิปจริงเฉพาะเมื่อครบรอบ poll — ตัวเรียกจึงเรียกได้ทุกลูปโดยไม่ต้องจับเวลาเอง
ct_touch_event_t ct_touch_poll_event(int elapsed_ms);

// ทางเดิมสำหรับผู้เรียกที่สนใจแค่การปัด — เรียกซ้อนกับตัวข้างบนไม่ได้
// ทั้งคู่อ่านชิปตัวเดียวกัน และท่าทางหนึ่งท่าถูกคืนให้ผู้เรียกได้ครั้งเดียว
ct_swipe_t ct_touch_poll(int elapsed_ms);
