// ตัวโฮสต์ของทุก page บนจอ — เป็นเจ้าของ active page, ที่เก็บ page frame ของแต่ละหน้า
// และนาฬิกาที่ต้องเดินต่อแม้หน้านั้นไม่ได้แสดงอยู่ (ADR-0002)
#pragma once

#include <stdbool.h>

#include "ct_model.h"
// `ct_ask_hit_t` — ปุ่มบนการ์ดคำขออนุญาต เรขาคณิตของมันเป็นของ `ct_ui`
#include "ct_ui.h"

// `ct_page_kind_t` ถูก generate ลง layout.h จาก tools/gen/pages.py — ชนิดของ page
// เป็นชุดปิดที่บอร์ดรู้จักตั้งแต่ตอนแฟลช (ADR-0004) ไม่ใช่สิ่งที่ Mac นิยามตอนรันไทม์
// การเพิ่มหน้าใหม่จึงแก้ที่ pages.py แล้วรัน export_layout.py ส่วนฝั่ง Swift (`PageKind`)
// มีเทสต์อ่าน layout.h มาเทียบให้
#include "layout.h"

// สร้างจอและทุกหน้า ต้องเรียกหลัง lv_init และมี display แล้ว
void ct_pages_init(void);

// page frame ของหน้ามาสคอตมาถึง — เก็บทับของเดิม แล้ววาดถ้าหน้านี้แสดงอยู่
void ct_pages_set_snapshot(const ct_snapshot_t *snap);

// เฟรมของหน้าอื่นมาถึง — คืน false เมื่อ JSON ไม่ใช่รูปร่างที่หน้านั้นรับได้
//
// ประตูเดียวสำหรับทุกหน้าที่ไม่ใช่มาสคอต: ตัวเรียกอ่านคีย์ `g` ได้อย่างเดียว ส่วนการ
// ตีความเนื้อในเป็นของหน้านั้น ซึ่งเป็นที่เดียวที่รู้ว่าเฟรมของตัวเองหน้าตาอย่างไร
bool ct_pages_set_frame(ct_page_kind_t kind, const char *json, int len);

// ผู้ใช้ปิดหน้านั้นบน Mac — ลืมทั้งเฟรมและถอนออกจากรอบ rotation
// (หน้าที่ปิดต้องหายไปจริง ไม่ใช่ swipe ไปเจอหน้าที่เขียนว่า "ปิดอยู่")
void ct_pages_forget(ct_page_kind_t kind);

// กติกาของจอที่ผู้ใช้ตั้งไว้บน Mac — นาฬิกายังเป็นของบอร์ด นี่คือค่าที่มันใช้จับเวลา
//
// `order` คือหน้าที่เปิดอยู่ *เรียงตามที่ผู้ใช้จัด* หน้าที่ไม่อยู่ในลิสต์นี้ไม่อยู่ในรอบเลย
// บอร์ดที่ยังไม่เคยได้แผนใช้ทุกหน้าตามลำดับ enum กับค่าจาก layout.toml
typedef struct {
    ct_page_kind_t order[CT_PAGE_KIND_COUNT];
    int count;
    // รอบหมุนเดินเองไหม — ปิดแล้วจอเปลี่ยนหน้าเฉพาะตอนถูกปัดหรือตอนมีเรื่องด่วน
    // (`rotation_ms` ยังถูกใช้อยู่ตอนปิด ดูที่ `ct_pages_attention`)
    bool auto_turn;
    int rotation_ms;
    int hold_ms;
    bool attention_jump;
} ct_page_plan_t;

// แปลงเฟรมค่าตั้ง (คีย์ `pl`) เป็นแผน — คืน false เมื่อ JSON ไม่ใช่รูปร่างที่รับได้
//
// แยกจากการ *ใช้* แผนเพราะเฟรมมาถึงคนละเธรดกับ LVGL: ตัวเรียกแปลงตรงที่รับ แล้วค่อย
// ส่งก้อนที่แปลงแล้วเข้าลูปหลัก เหมือนที่ snapshot ทำ
bool ct_pages_parse_plan(const char *json, int len, ct_page_plan_t *out);

void ct_pages_set_plan(const ct_page_plan_t *plan);

// ผู้ใช้ปัดหน้าเอง — เดินไปหน้าถัดไป (`forward`) หรือหน้าก่อนหน้าตามลำดับที่เขาจัดไว้
// แล้วยึดหน้านั้นไว้ตามระยะ hold ก่อนกลับเข้ารอบ
//
// หน้าที่ผู้ใช้ปิดหรือยังไม่เคยได้เฟรมถูกข้ามไป ไม่ใช่แสดงเป็นหน้าว่าง — ปัดหนึ่งครั้ง
// ต้องได้หน้าที่มีอะไรให้ดูเสมอ ไม่ใช่หน้าที่เขียนว่า "ปิดอยู่"
void ct_pages_step(bool forward);

// มีเรื่องด่วนบนหน้ามาสคอต — กระโดดไปหามันถ้าผู้ใช้เปิดสวิตช์นี้ไว้
//
// เป็นคำสั่งจากเหตุการณ์ ไม่ใช่จากผู้ใช้ จึงไม่ยึดหน้าไว้เหมือน `ct_pages_step`:
// การเตือนที่ผ่านไปแล้วต้องไม่ค้างจอไว้อีกห้านาที
//
// ทำงานแม้รอบหมุนถูกปิด — คนที่ปิดรอบหมุนบอกว่า "อย่าเปลี่ยนหน้าเพราะเวลาผ่านไป"
// ไม่ได้บอกว่า "อย่าบอกฉันว่ามีคนรออยู่" ซึ่งเป็นเหตุผลที่เครื่องนี้มีอยู่ และมีสวิตช์
// ของตัวเองให้ปิดแยกอยู่แล้ว
void ct_pages_attention(void);

// นิ้วที่แตะจอตอนนี้ตกปุ่มไหนของการ์ดคำขออนุญาต — `CT_ASK_HIT_NONE` เมื่อหน้ามาสคอต
// ไม่ได้อยู่บนจอ ซึ่งเป็นข้อที่ `ct_ui` ตอบเองไม่ได้ มันไม่รู้ว่าใครกำลังถูกแสดงอยู่
//
// การ์ดที่ถูกหน้าอื่นบังอยู่ต้องกดไม่ได้ ไม่ใช่กดได้แบบมองไม่เห็น
ct_ask_hit_t ct_pages_ask_hit(int x, int y);

// id ของคำขอที่กำลังแสดงอยู่ — สตริงว่างเมื่อไม่มี หรือเมื่อหน้ามาสคอตไม่ได้อยู่บนจอ
const char *ct_pages_ask_id(void);

// รายการ PageKind ที่บอร์ดตัวนี้รู้จัก เป็น JSON พร้อมส่งกลับไปให้ Mac (ADR-0006)
// เขียนลง `out` แล้วคืนความยาว
int ct_pages_capability_json(char *out, int size);

// สถานะลิงก์เป็นของทั้งเครื่อง ไม่ใช่ของหน้าใดหน้าหนึ่ง — โฮสต์ส่งต่อให้หน้าที่สนใจ
void ct_pages_set_connected(bool connected);
// ที่อยู่ของบอร์ดไม่ขึ้นจอแล้ว — มันอยู่ในหน้าตั้งค่าบน Mac ที่เดียว ซึ่งคือที่ที่ผู้ใช้
// ต้องเอาไปกรอกอยู่แล้ว · ป้ายเดียวที่หมายถึงชื่อหน้า/ที่อยู่/คำเตือน ต้องถอดรหัสก่อนอ่านทุกครั้ง
void ct_pages_set_link(bool ble, bool wifi);

// เดินเวลาไป `elapsed_ms` — นาฬิกาของทุกหน้าเดินที่นี่ ส่วนอนิเมชันเดินเฉพาะหน้าที่แสดงอยู่
void ct_pages_tick(int elapsed_ms);
