// หน้ามาสคอต — โครงเดียวกับ tools/gen/screen.py
//
// ที่นี่วาดอย่างเดียว: page frame ที่วาดเป็นของ `ct_pages` และนาฬิกาทุกเรือนก็เดินที่นั่น
// (ADR-0002) หน้านี้ได้พอยน์เตอร์ไปอ่านตอน init แล้วถูกบอกให้วาดใหม่เมื่อของที่อ่านอยู่เปลี่ยน
#pragma once

#include <stdint.h>

#include "ct_model.h"
#include "lvgl.h"

// สร้าง widget ทั้งหมดลงใต้ `parent` แล้วผูกกับ page frame ที่จะวาด
// ต้องเรียกหลัง lv_init และมี display แล้ว
void ct_ui_init(lv_obj_t *parent, const ct_snapshot_t *frame);

// page frame ที่ผูกไว้เปลี่ยนไปแล้ว — วาดใหม่ทั้งใบ
void ct_ui_redraw(void);

// ตัวโฮสต์เพิ่งเดินนาฬิกาโควตาไปหนึ่งวินาที — วาดเฉพาะส่วนที่ตัวเลขนั้นโผล่อยู่
void ct_ui_redraw_usage(void);

// มี snapshot สดอยู่ไหม — ไม่ว่าจะมาทาง BLE หรือ LAN ก็ตาม หลุดแล้วมาสคอตเป็นสีเทา
// ไม่มีไอคอน ไม่มีข้อความ · เรื่องของแถบบนเป็นของ `ct_topbar_set_connected`
void ct_ui_set_connected(bool connected);

// สภาพอากาศที่ฟ้าของหน้ามาสคอตจะวาด — **รหัส WMO จากเฟรมของหน้าอากาศ** ไม่ใช่จาก
// snapshot (ADR-0012) · `ct_pages` เป็นคนตัดสินว่าเฟรมที่มันแคชไว้ยังใช้ได้ไหม แล้วบอกมา
// ที่นี่ เพราะกติกา stale อยู่ที่เดียวกับที่เดินอายุของทุกหน้าอยู่แล้ว
// `valid == false` = ฟ้าตามเวลาแบบไม่มีอากาศ ซึ่งเป็นฟ้าที่หน้านี้เคยมีมาตลอด
void ct_ui_set_weather(int code, bool valid);

// หลุดลิงก์มากี่วินาทีแล้ว — ตัวเลขนี้แทนที่นาฬิกาตัวใหญ่ตอนไม่มีใครป้อน snapshot
// (นาฬิกาไม่เดินเองบนบอร์ด เลขที่ค้างจึงไม่ใช่เวลาอีกต่อไป) ตัวนับอยู่ที่ `ct_pages`
// เพราะมันต้องเดินต่อขณะที่หน้าอื่นอยู่บนจอ เหมือน countdown ของโควตาและอายุของทุกหน้า
void ct_ui_set_offline_secs(int secs);

// หน้านี้แสดงนาฬิกาตัวใหญ่ / แผงโควตาเต็มอยู่ไหม — แถบบน (`ct_topbar`) ถามก่อนวาดของ
// ของมัน เพราะกติกาคือ "แถบไม่พูดซ้ำสิ่งที่หน้านั้นแสดงใหญ่กว่าอยู่แล้ว" ตัวกติกาอยู่ที่
// `ct_topbar` ส่วน *ข้อเท็จจริง* ว่าหน้านี้แสดงอะไรอยู่เป็นของที่นี่ ซึ่งเป็นคนตัดสิน
bool ct_ui_shows_clock(void);
bool ct_ui_shows_usage(void);

// เปอร์เซ็นต์ -> สีตามระดับ · แถบบนใช้สูตรเดียวกันกับแผงเต็ม ไม่ใช่สำเนาของมัน
uint16_t ct_ui_usage_color(int percent);

// สีของแถบ — เกณฑ์ % *กับ* จังหวะการใช้เทียบเวลาที่ผ่านไปในหน้าต่าง
// แถบบนเรียกตัวนี้ ไม่ใช่ `ct_ui_usage_color` เปล่าๆ: ตัวเลขเดียวกันที่แถบบนเขียวแต่ที่
// แผงเต็มแดง คือจอที่พูดสองอย่างเกี่ยวกับเลขตัวเดียวกัน
uint16_t ct_ui_usage_bar_color(const ct_usage_t *u, int window);

// ปุ่มไหนบนการ์ดคำขออนุญาตที่พิกัดนี้ตก
typedef enum {
    CT_ASK_HIT_NONE = 0,  // ไม่มีการ์ดอยู่ หรือ นิ้วตกนอกปุ่มทั้งสอง
    CT_ASK_HIT_DENY,
    CT_ASK_HIT_ALLOW,
} ct_ask_hit_t;

// พิกัดของภาพ (0,0 = มุมบนซ้าย) -> ปุ่ม · เรขาคณิตอยู่ที่นี่ที่เดียว ผู้เรียกไม่ต้องรู้
// ว่าปุ่มอยู่ตรงไหน และไม่มีสำเนาของตัวเลขชุดเดียวกันไปอยู่ที่สอง
//
// นิ้วที่ตกลง *ระหว่าง* ปุ่มได้ `NONE` โดยตั้งใจ — นั่นคือทั้งเหตุผลที่ช่องว่างนั้นมีอยู่
// (ADR-0014) การเล็งไม่แม่นต้องจบลงที่ "ไม่มีอะไรเกิดขึ้น" ไม่ใช่ที่คำตอบใดคำตอบหนึ่ง
ct_ask_hit_t ct_ui_ask_hit(int x, int y);

// id ของคำขอที่อยู่บนจอตอนนี้ — สตริงว่างเมื่อไม่มี · คำตอบต้องผูกกับ *ใบ* ไม่ใช่
// แค่ปุ่มที่กด ใบที่หมดเวลาไปแล้วระหว่างที่นิ้วกำลังลงจึงตกไปเงียบๆ ที่ฝั่ง Mac
const char *ct_ui_ask_id(void);

// เดินอนิเมชันไป `elapsed_ms` เรียกเมื่อหน้านี้เป็น active page เท่านั้น
// เวลามาจากตัวโฮสต์ ไม่ใช่ค่าคงที่ที่นี่ — นาฬิกาของหน้ากับของโฮสต์ต้องเป็นก้อนเดียวกัน
void ct_ui_tick(int elapsed_ms);
